export function t(lang: Lang, key: string, fallback?: string): string {
  const entry = dict[key];
  if (entry) return entry[lang] || entry.en;
  return fallback ?? key;
}

export function useT(lang: Lang) {
  return useCallback((key: string, fallback?: string) => t(lang, key, fallback), [lang]);
}

export function pick(value: Bilingual | undefined, lang: Lang): string {
  if (!value) return "";
  return value[lang] || value.en || value.si || "";
}

export function missingLangs(value: Bilingual): string[] {
  const out: string[] = [];
  if (!value.en?.trim()) out.push("English");
  if (!value.si?.trim()) out.push("Sinhala");
  return out;
}
